import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = await readFile(resolve(root, "lib/sync/capabilities.ts"), "utf8");
const resourcesMatch = source.match(/export const CAPABILITY_RESOURCES = \[([\s\S]*?)\] as const;/);
const actionsMatch = source.match(/export const CAPABILITY_ACTIONS = \[([\s\S]*?)\] as const;/);
if (!resourcesMatch || !actionsMatch) throw new Error("DEVICE_V2_CAPABILITY_REGISTRY_NOT_FOUND");

const quotedValues = (text) => [...text.matchAll(/"([a-z_]+)"/g)].map((match) => match[1]);
const resources = quotedValues(resourcesMatch[1]);
const actions = quotedValues(actionsMatch[1]);
if (!resources.length || !actions.length) throw new Error("DEVICE_V2_CAPABILITY_REGISTRY_EMPTY");

const fullCapabilities = resources.flatMap((resource) => actions.map((action) => `${resource}.${action}`));
const json = JSON.stringify(fullCapabilities).replaceAll("'", "''");
const sql = `-- Generated by scripts/generate-v2-owner-policy-migration.mjs. Do not edit manually.\n-- One-time cutover seed: existing active owners receive the full explicit V2 policy.\nINSERT OR IGNORE INTO group_policy_revisions (group_id, revision, updated_at)\nSELECT DISTINCT group_id, 1, unixepoch() * 1000 FROM devices;\n\nINSERT OR IGNORE INTO device_policies (device_id, group_id, revision, capabilities_json, updated_at, updated_by)\nSELECT d.device_id, d.group_id, 1, '${json}', unixepoch() * 1000, d.device_id\nFROM devices d\nWHERE d.is_active = 1 AND d.role = 'owner';\n`;
await writeFile(resolve(root, "workers/cocktail-ai/migrations/20260820_seed_v2_owner_policies.sql"), sql, "utf8");
console.log(`Generated ${fullCapabilities.length} capabilities for V2 owner seed.`);
